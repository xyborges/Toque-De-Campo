"""Build the P1k QA fixture for Linux in an isolated worktree.

Reserve project.godot, export_presets.cfg and the paths generated by
export_true_fpp_p1k_qa.benchmark_sources(), including the two .gd.uid files.
"""
import argparse
from contextlib import ExitStack
from hashlib import sha256
import json
import os
from pathlib import Path
import subprocess

from export_true_fpp_p1k_qa import ROOT, QA_SCENE, benchmark_sources, file_hash, gameplay_hashes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--engine", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    output = args.output.resolve()
    if output == ROOT or ROOT in output.parents:
        parser.error("Choose an output directory outside the project")
    output.mkdir(parents=True, exist_ok=False)
    engine = args.engine.resolve()
    if engine.name.endswith("_console.exe"):
        engine = engine.with_name(engine.name.removesuffix("_console.exe") + ".exe")

    project = ROOT / "project.godot"
    presets = ROOT / "export_presets.cfg"
    original_project = project.read_bytes()
    original_presets = presets.read_bytes()
    old_scene = b'run/main_scene="res://scenes/main.tscn"'
    if original_project.count(old_scene) != 1 or b"[preset.3]" in original_presets:
        raise RuntimeError("Unexpected project scene or export preset")
    temporary_project = original_project.replace(old_scene, f'run/main_scene="res://{QA_SCENE}"'.encode())

    # Copy the project's server preset, enabling only the QA feature and QA
    # fixture assets. Do not change the normal Linux Server preset.
    start = original_presets.index(b"[preset.2]")
    server_preset = original_presets[start:]
    preset = server_preset.replace(b"[preset.2]", b"[preset.3]").replace(
        b"[preset.2.options]", b"[preset.3.options]")
    preset = preset.replace(b'name="Linux Server"', b'name="Linux P1k QA"')
    preset = preset.replace(b'custom_features=""', b'custom_features="qa"')
    preset = preset.replace(b"dedicated_server=true", b"dedicated_server=false")
    preset = preset.replace(b"qa/*,tests/*", b"tests/*")
    if b'name="Linux P1k QA"' not in preset or b'custom_features="qa"' not in preset or b"qa/*" in preset:
        raise RuntimeError("Cannot derive the QA preset safely")
    temporary_presets = original_presets + b"\n" + preset
    sources = benchmark_sources()
    targets = [ROOT / path for path in sources]
    uid_paths = [path.with_suffix(".gd.uid") for path in targets if path.suffix == ".gd"]
    if any(path.exists() for path in targets + uid_paths):
        raise RuntimeError("QA staging paths already exist; inspect before exporting")
    gameplay = gameplay_hashes()
    executable = output / "P1kBenchmark.x86_64"
    with ExitStack() as cleanup:
        for path in uid_paths:
            cleanup.callback(path.unlink, missing_ok=True)
        for name, data in sources.items():
            path = ROOT / name
            with path.open("xb") as stream:
                cleanup.callback(path.unlink)
                stream.write(data)
        try:
            project.write_bytes(temporary_project)
            presets.write_bytes(temporary_presets)
            with (output / "export.log").open("wb") as log:
                result = subprocess.run([
                    str(engine), "--headless", "--path", str(ROOT), "--export-release",
                    "Linux P1k QA", str(executable),
                ], cwd=ROOT, stdout=log, stderr=subprocess.STDOUT, timeout=420,
                    creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
        finally:
            changed = []
            for path, original, temporary in ((project, original_project, temporary_project),
                                               (presets, original_presets, temporary_presets)):
                current = path.read_bytes()
                if current == temporary:
                    path.write_bytes(original)
                elif current != original:
                    changed.append(path.name)
            if changed:
                raise RuntimeError(f"Files changed during export; inspect before restoring: {changed}")
    log = (output / "export.log").read_text(encoding="utf-8", errors="replace")
    if result.returncode or "ERROR:" in log or not executable.is_file():
        raise RuntimeError(f"Linux QA export failed; see {output / 'export.log'}")
    if gameplay_hashes() != gameplay:
        raise RuntimeError("Gameplay changed during export")
    manifest = {
        "fixtures_sha256": {name: sha256(data).hexdigest() for name, data in sources.items()},
        "exe_sha256": file_hash(executable), "pack_sha256": file_hash(executable.with_suffix(".pck")),
        "project_sha256": sha256(original_project).hexdigest(),
        "export_presets_sha256": sha256(original_presets).hexdigest(),
        "gameplay_sha256": gameplay,
    }
    (output / "p1k_export.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Linux QA export: {executable}")


if __name__ == "__main__":
    main()
